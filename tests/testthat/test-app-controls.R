test_that("installed app controls apply human moves and honor play mode", {
  skip_if_not_installed("shiny")
  root <- system.file("shiny", "multixoR", package = "multixoR")
  module <- new.env(parent = globalenv())
  sys.source(file.path(root, "modules", "mod_controls.R"), envir = module)
  state <- shiny::reactiveValues(game = mxo_new_game(n = 3L, k = 3L), difficulty = "easy")
  shiny::testServer(module$mxo_mod_controls_server, args = list(state = state), {
    session$setInputs(mode = "hvh", difficulty = "easy")
    session$setInputs(human_move = "present:0:0:0", play_move = 1L)
    expect_length(state$game$history, 1L)
    session$setInputs(human_move = "present:0:0:0", play_move = 2L)
    expect_length(state$game$history, 1L) # stale selection must not choose another cell
    session$setInputs(undo = 1L)
    expect_length(state$game$history, 0L)
    session$setInputs(mode = "hvai", human_move = "present:0:0:0", play_move = 3L)
    expect_length(state$game$history, 2L)
    session$setInputs(new_game = 1L)
    expect_length(state$game$history, 0L)
    session$setInputs(mode = "avai", human_move = "present:0:0:0", play_move = 4L)
    expect_length(state$game$history, 0L)
    session$setInputs(ai_move = 1L)
    expect_length(state$game$history, 1L)
  })
})
